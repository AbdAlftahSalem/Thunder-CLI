// Copies the official templates into lib/src/core/consts/bundled_templates.dart
// so `thunder init` still works offline.
//
//   git clone -b getx  https://github.com/AbdAlftahSalem/Thunder-Template /tmp/tpl_getx
//   git clone -b bloc  https://github.com/AbdAlftahSalem/Thunder-Template /tmp/tpl_bloc
//   git clone -b cubit https://github.com/AbdAlftahSalem/Thunder-Template /tmp/tpl_cubit
//   dart run tool/bundle_templates.dart /tmp/tpl_getx /tmp/tpl_bloc /tmp/tpl_cubit
import 'dart:convert';
import 'dart:io';

import 'package:path/path.dart' as p;

const _include = [
  'pubspec.yaml',
  'analysis_options.yaml',
  'lib',
  'test',
  'assets'
];

void main(List<String> args) {
  if (args.length != 3) {
    stderr.writeln(
        'Usage: dart run tool/bundle_templates.dart <getx-dir> <bloc-dir> <cubit-dir>');
    exit(64);
  }
  final styles = ['getx', 'bloc', 'cubit'];
  final out = StringBuffer()
    ..writeln(
        '// GENERATED by tool/bundle_templates.dart — do not edit by hand.')
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln()
    ..writeln(
        '/// Offline copy of the official templates (Thunder-Template repository),')
    ..writeln(
        '/// used by `thunder init` when the download fails or with `--offline`.')
    ..writeln('/// style => (path => content).')
    ..writeln('const Map<String, Map<String, String>> bundledTemplates = {');
  for (var i = 0; i < styles.length; i++) {
    final root = args[i];
    out.writeln("  '${styles[i]}': {");
    final files = <String>[];
    for (final entry in _include) {
      final path = p.join(root, entry);
      if (File(path).existsSync()) files.add(entry);
      if (Directory(path).existsSync()) {
        files.addAll(Directory(path)
            .listSync(recursive: true)
            .whereType<File>()
            .map((f) => p.relative(f.path, from: root).replaceAll(r'\', '/')));
      }
    }
    files.sort();
    for (final file in files) {
      final String content;
      try {
        content = utf8.decode(File(p.join(root, file)).readAsBytesSync());
      } on FormatException {
        continue; // binary files are not bundled
      }
      if (content.contains("'''")) {
        throw StateError('$file contains three single quotes');
      }
      out.writeln("    '$file': r'''$content''',");
    }
    out.writeln('  },');
  }
  out.writeln('};');
  const target = 'lib/src/core/consts/bundled_templates.dart';
  File(target).writeAsStringSync(out.toString());
  Process.runSync('dart', ['format', target]);
  stdout.writeln('✅ $target');
}
